const CACHE = 'focusread-' + VERSION;

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // cache: 'reload' bypasses the HTTP cache so we never precache stale files
    await Promise.all(PRECACHE.map(url => cache.add(new Request(url, { cache: 'reload' }))));
    // Activate immediately: on first install so the app works offline right away, and on updates
    // so a broken older copy is replaced without the user deleting site data.
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter(k => k.startsWith('focusread-') && k !== CACHE).map(k => caches.delete(k)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', event => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

// "Share → FocusRead" from another app (Files, Drive, WhatsApp…): the system POSTs the files here.
// Keep them in a small cache and open the app, which imports them (see handleIncoming in app.js).
const SHARE_CACHE = 'fr-share';
async function receiveShare(req) {
  try {
    const form = await req.formData();
    const cache = await caches.open(SHARE_CACHE);
    const stamp = Date.now();
    let n = 0;
    for (const f of form.getAll('files')) {
      if (!f || typeof f === 'string' || !f.size) continue;
      await cache.put(`/__share/${stamp}/${n++}`, new Response(f, { headers: { 'Content-Type': f.type || 'application/octet-stream', 'X-Name': encodeURIComponent(f.name || 'file') } }));
    }
    const text = [form.get('title'), form.get('text'), form.get('url')].map(v => (typeof v === 'string' ? v : '')).filter(Boolean);
    if (text.length) await cache.put(`/__share/${stamp}/text`, new Response(JSON.stringify({ title: typeof form.get('title') === 'string' ? form.get('title') : '', text: typeof form.get('text') === 'string' ? form.get('text') : '', url: typeof form.get('url') === 'string' ? form.get('url') : '' }), { headers: { 'Content-Type': 'application/json' } }));
  } catch (e) {}
  return Response.redirect('/?share=1', 303);
}

self.addEventListener('fetch', event => {
  const req = event.request;
  if (req.method === 'POST' && new URL(req.url).pathname === '/share-target') { event.respondWith(receiveShare(req)); return; }
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith('/api/')) return; // sync API: always network, never cached

  // App navigations (including share-target URLs with ?text=…) → cached app shell.
  if (req.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      const shell = await cache.match('/index.html');
      if (shell) return shell;
      try { return await fetch(req); } catch { return new Response('Offline', { status: 503, headers: { 'Content-Type': 'text/plain' } }); }
    })());
    return;
  }

  // Static assets: cache-first, then network (and store successful same-origin responses).
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(req, { ignoreSearch: true });
    if (hit) return hit;
    try {
      const res = await fetch(req);
      if (res.ok && res.type === 'basic') cache.put(req, res.clone());
      return res;
    } catch (e) {
      if (req.destination === 'image') { const icon = await cache.match('/icons/icon-192.png'); if (icon) return icon; }
      throw e;
    }
  })());
});
